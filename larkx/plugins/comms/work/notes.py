def profile_senders(profile) -> dict:
    """会话白名单 {user_id: 名字}; 空表示所有人。"""
    try:
        data = json.loads(getattr(profile, 'senders', None) or '{}')
    except (TypeError, ValueError):
        return {}
    return {str(k): v for k, v in data.items()} if isinstance(data, dict) else {}


def sender_allowed(profile, sender_id) -> bool:
    """会话白名单为空时所有人都算; 非空时只有名单里的人。"""
    senders = profile_senders(profile)
    return not senders or str(sender_id) in senders


# 回复格式: 开头写收件人名字(纯文字, 不真的 @), 一眼看出是回给谁的
ADDRESS_NOTE = ('回复的第一行以收件人的名字加冒号开头, 例如「张三：」; 同时回给几个人就用顿号隔开, 例如「张三、李四：」。'
                '只写名字文字, 不要用 --mention 真的 @ 人。')


def profile_note(profile, listen: bool = False) -> str:
    """会话配置附在提示词里的说明: 旁听规则、本会话专属指令、相关代码目录。没有配置时是空字符串。"""
    if profile is None:
        return ''
    parts = []
    if listen:
        parts.append(LISTEN_NOTE.format(chat=profile.chat_id))
    if (profile.workdir or '').strip():
        parts.append(f'本会话相关代码目录: {profile.workdir.strip()}')
    if (profile.instruction or '').strip():
        parts.append(f'本会话专属指令(本人设置): {profile.instruction.strip()}')
    return '; '.join(parts)
